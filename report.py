"""Per-call intelligence report: a PDF (reportlab), or a plain-text version if reportlab is not installed."""
import io
import json
from datetime import datetime
from xml.sax.saxutils import escape

import personas

TITLE = "Dorothy Decoy System — Intelligence Report"
FOOTER = "Generated by Dorothy Decoy System — For internal fraud investigation use only"

try:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import letter
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import inch
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
    HAVE_REPORTLAB = True
except ImportError:  # pragma: no cover - exercised by a test that blocks the import
    HAVE_REPORTLAB = False


# ---------- data ----------

def _when(iso):
    try:
        return datetime.fromisoformat(iso).strftime("%Y-%m-%d %H:%M UTC")
    except (TypeError, ValueError):
        return "unknown"


def _duration(call):
    try:
        secs = int((datetime.fromisoformat(call["ended_at"]) - datetime.fromisoformat(call["started_at"])).total_seconds())
    except (TypeError, ValueError, KeyError):
        return "not ended"
    secs = max(secs, 0)
    return f"{secs // 60}m {secs % 60:02d}s"


def _load(call):
    """Flatten a calls row into everything the report needs. Tolerates a missing extraction and an empty transcript."""
    def js(raw, default):
        try:
            v = json.loads(raw) if raw else default
            return v if v is not None else default
        except ValueError:
            return default
    ex = js(call.get("extraction_json"), None)
    persona = personas.get_persona(call.get("persona_id"))
    return {
        "id": call["id"], "date": _when(call.get("started_at")), "duration": _duration(call),
        "persona": f"{persona['name']} ({persona['id']})" if call.get("persona_id") else "not recorded",
        "transcript": js(call.get("transcript_json"), []), "ex": ex,
        "prior": js(call.get("prior_context"), None),
    }


def risk_band(score):
    """(label, hex color): green < 40, orange 40-70, red > 70."""
    return ("LOW", "#2e9e5b") if score < 40 else ("MEDIUM", "#f79009") if score <= 70 else ("HIGH", "#d92d20")


def _entity_row(e):
    return [str(e.get("type", "")), str(e.get("bank_name", "") or "-"), str(e.get("routing_number", "") or "-"),
            str(e.get("account_number", "") or "-"), str(e.get("value", "") or "-")]


def _speaker(m):
    return m.get("name") or m.get("speaker") or "?"


# ---------- plain text fallback ----------

def build_text(call):
    d = _load(call)
    ex = d["ex"]
    out = [TITLE, "=" * len(TITLE), "",
           f"Call ID:   {d['id']}", f"Date:      {d['date']}", f"Duration:  {d['duration']}", f"Persona:   {d['persona']}", ""]
    if ex:
        label, _ = risk_band(ex.get("risk_score", 0))
        out += [f"RISK SCORE: {ex.get('risk_score', 0)}/100 ({label})",
                f"Scam type: {ex.get('scam_type')}   Is scam: {'yes' if ex.get('is_scam') else 'no'}", "", "Red flags:"]
        out += [f"  - {f}" for f in ex.get("red_flags", [])] or ["  (none)"]
        out += ["", "Extracted entities:"]
        out += ["  " + " | ".join(_entity_row(e)) for e in ex.get("entities", [])] or ["  (none)"]
        out += ["", "Scam script phrases:"]
        out += [f'  - "{x}"' for x in ex.get("script_lines", [])] or ["  (none)"]
    else:
        out += ["Extraction has not been run for this call."]
    out += ["", "Transcript:"]
    out += [f"  {_speaker(m)}: {m.get('text', '')}" for m in d["transcript"]] or ["  (empty)"]
    out += ["", "Summary:", f"  {ex.get('summary', '') if ex else 'n/a'}", "", FOOTER]
    return "\n".join(out)


# ---------- PDF ----------

def _safe(text):
    """Escape for reportlab markup and drop characters the built-in Helvetica font cannot draw."""
    return escape(str(text).encode("cp1252", "replace").decode("cp1252"))


def build_pdf(call):
    d = _load(call)
    ex = d["ex"]
    ss = getSampleStyleSheet()
    body = ParagraphStyle("body", parent=ss["BodyText"], fontSize=9.5, leading=13)
    small = ParagraphStyle("small", parent=body, fontSize=8.5, leading=11)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], fontSize=12, spaceBefore=12, spaceAfter=4, textColor=colors.HexColor("#182230"))
    title = ParagraphStyle("title", parent=ss["Title"], fontSize=18, leading=22, alignment=0, textColor=colors.HexColor("#182230"))
    P = lambda t, s=body: Paragraph(_safe(t), s)  # noqa: E731
    PB = lambda label, value, s=body: Paragraph(f"<b>{_safe(label)}</b> {_safe(value)}", s)  # noqa: E731  (bold label, escaped value)

    story = [P(TITLE, title), Spacer(1, 4)]

    meta = Table([[P("Call ID", small), P(d["id"], small)], [P("Date", small), P(d["date"], small)],
                  [P("Duration", small), P(d["duration"], small)], [P("Persona", small), P(d["persona"], small)]],
                 colWidths=[1.1 * inch, 5.4 * inch])
    meta.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#d0d5dd")),
                              ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f2f4f7")), ("VALIGN", (0, 0), (-1, -1), "MIDDLE")]))
    story += [meta, Spacer(1, 10)]

    if ex:
        score = ex.get("risk_score", 0)
        label, hexcolor = risk_band(score)
        big = ParagraphStyle("big", parent=body, fontSize=30, leading=34, textColor=colors.white, alignment=1)
        lab = ParagraphStyle("lab", parent=body, fontSize=10, leading=13, textColor=colors.white, alignment=1)
        box = Table([[Paragraph(f"{int(score)}", big)], [Paragraph(f"RISK SCORE / 100 — {label}", lab)]], colWidths=[2.2 * inch])
        box.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(hexcolor)), ("TOPPADDING", (0, 0), (-1, -1), 6),
                                 ("BOTTOMPADDING", (0, 0), (-1, -1), 6)]))
        verdict = [PB("Scam type:", ex.get("scam_type")), PB("Is scam:", "YES" if ex.get("is_scam") else "no")]
        if d["prior"] and d["prior"].get("prior_calls"):
            verdict.append(PB("Repeat caller:", f"{d['prior']['prior_calls']} earlier call(s), last on {d['prior'].get('last_call_date')}"))
        side = Table([[box, verdict]], colWidths=[2.4 * inch, 4.1 * inch])
        side.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "MIDDLE")]))
        story += [side, P("Red flags", h2)]
        flags = ex.get("red_flags", [])
        story += [P("• " + f.replace("_", " "), body) for f in flags] or [P("None detected.", body)]

        story.append(P("Extracted entities", h2))
        ents = ex.get("entities", [])
        if ents:
            rows = [[Paragraph(f"<b>{h}</b>", small) for h in ("Type", "Bank", "Routing", "Account", "Value")]]
            rows += [[P(c, small) for c in _entity_row(e)] for e in ents]
            t = Table(rows, colWidths=[1.2 * inch, 1.6 * inch, 1.05 * inch, 1.4 * inch, 1.25 * inch], repeatRows=1)
            t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#d0d5dd")),
                                   ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eaf0ff")), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
            story.append(t)
        else:
            story.append(P("None extracted.", body))

        story.append(P("Scam script phrases", h2))
        story += [P(f"“{x}”", body) for x in ex.get("script_lines", [])] or [P("None extracted.", body)]
    else:
        story += [P("Extraction", h2), P("Extraction has not been run for this call yet, so risk, entities and flags are unavailable.", body)]

    story.append(P("Transcript", h2))
    decoy = ParagraphStyle("decoy", parent=body, backColor=colors.HexColor("#eaf0ff"), leftIndent=0, rightIndent=60, borderPadding=4, spaceAfter=7)
    caller = ParagraphStyle("caller", parent=body, backColor=colors.HexColor("#e8f7ee"), leftIndent=60, rightIndent=0, borderPadding=4, spaceAfter=7)
    if d["transcript"]:
        for m in d["transcript"]:
            style = decoy if m.get("speaker") == "Dorothy" else caller
            story.append(Paragraph(f"<b>{_safe(_speaker(m))}:</b> {_safe(m.get('text', ''))}", style))
    else:
        story.append(P("(empty transcript)", body))

    story += [P("Summary", h2), P((ex or {}).get("summary") or "No summary available.", body)]

    def footer(canvas, doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 7.5)
        canvas.setFillColor(colors.HexColor("#667085"))
        canvas.drawString(0.75 * inch, 0.5 * inch, FOOTER.encode("cp1252", "replace").decode("cp1252"))
        canvas.drawRightString(letter[0] - 0.75 * inch, 0.5 * inch, f"Page {doc.page}")
        canvas.restoreState()

    buf = io.BytesIO()
    SimpleDocTemplate(buf, pagesize=letter, leftMargin=0.75 * inch, rightMargin=0.75 * inch, topMargin=0.75 * inch,
                      bottomMargin=0.8 * inch, title=TITLE, author="Dorothy Decoy System").build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()


def build_report(call):
    """(content bytes, media type, file extension): PDF when reportlab is available, plain text otherwise."""
    if HAVE_REPORTLAB:
        return build_pdf(call), "application/pdf", "pdf"
    return build_text(call).encode("utf-8"), "text/plain; charset=utf-8", "txt"
